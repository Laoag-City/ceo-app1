const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const dir = path.resolve(__dirname, '../features/printing');
async function preview(kind = 'building', failure = '', query = '') {
  const dom = new JSDOM(fs.readFileSync(path.join(dir, 'project-summary.html'), 'utf8'), {
    url: `http://localhost/project-summary.html?kind=${kind}&id=1${query}`, runScripts: 'outside-only'
  });
  const calls = [];
  dom.window.fetch = async url => {
    calls.push(url);
    let data;
    if (url === '/api/auth/session') data = { user: { username: 'test-login-name' } };
    else if (url === '/api/profile') data = { profile: { display_name: 'Test display name' } };
    else if (url.endsWith('/inspections')) data = { inspections: [{ inspection_type: 'Final', inspection_date: '2026-09-24', findings: 'A'.repeat(800), result: 'Passed' }] };
    else if (url.endsWith('/checklist')) data = { checklist_state: { cl01: true } };
    else data = { id: 1, project_title: 'Sample <img onerror=bad()>', lot_numbers: ['Lot 2'], matrix: [{ discipline_name: 'Electrical', signature_status: 'Approved', date_checked: '2026-09-20' }], sub_permits: [{ sub_project_title: 'Annex', matrix: [] }] };
    return { ok: !(failure && url.includes(failure)), status: failure === '/api/auth/session' ? 401 : 500, json: async () => data };
  };
  for (const file of ['project-identity.js', 'occupancy-checklist.js', 'project-summary.js']) dom.window.eval(fs.readFileSync(path.resolve(__dirname, file.startsWith('project-summary.') ? '../features/printing/' + file : '../assets/permits/' + file), 'utf8'));
  await new Promise(resolve => setImmediate(resolve));
  return { dom, calls, document: dom.window.document };
}
test('building: saved details, sub-permits, safe text and no remarks or logs', async () => {
  const { dom, calls, document: d } = await preview();
  assert.equal(d.querySelector('#print').disabled, false);
  assert.match(d.querySelector('main').textContent, /BP-1/);
  assert.match(d.querySelector('main').textContent, /Annex/);
  assert.ok(calls.includes('/api/permits/1/inspections'));
  assert.match(d.querySelector('main').textContent, /Inspections/);
  assert.match(d.querySelector('main').textContent, /Passed/);
  assert.match(d.querySelector('footer').textContent, /Generated by Test display name/);
  assert.doesNotMatch(d.querySelector('footer').textContent, /test-login-name/);
  assert.equal(d.querySelector('main script, main img[onerror]'), null);
  assert.equal(calls.some(url => url.includes('/project-records/')), false);
  assert.equal(d.querySelector('#include-logs'), null);
  assert.doesNotMatch(d.querySelector('main').textContent, /Remarks|Logs/);
  dom.window.close();
});
test('occupancy: inspections and shared requirements use saved values', async () => {
  const { dom, calls, document: d } = await preview('occupancy');
  assert.equal(calls.some(url => url.includes('/project-records/')), false);
  assert.doesNotMatch(d.querySelector('main').textContent, /Remarks|Logs/);
  assert.match(d.querySelector('main').textContent, /OP-1/);
  assert.match(d.querySelector('footer').textContent, /Generated by Test display name/);
  assert.doesNotMatch(d.querySelector('footer').textContent, /test-login-name/);
  assert.match(d.querySelector('main').textContent, /Passed/);
  assert.match(d.querySelector('main').textContent, /Duly Accomplished Application FormSubmitted/);
  assert.match(d.querySelector('main').textContent, /Not marked submitted/);
  assert.equal(d.querySelector('#print').disabled, false);
  dom.window.close();
});
for (const failure of ['/api/auth/session', '/api/profile', '/inspections']) test(`failed ${failure} prevents partial printing`, async () => {
  const { dom, document: d } = await preview('occupancy', failure);
  assert.equal(d.querySelector('#print').disabled, true);
  assert.equal(d.querySelector('main').hidden, true);
  assert.equal(d.querySelector('main').textContent, '');
  dom.window.close();
});
test('invalid reference makes no API requests', async () => {
  const { dom, calls } = await preview('invalid');
  assert.equal(calls.length, 0);
  dom.window.close();
});
