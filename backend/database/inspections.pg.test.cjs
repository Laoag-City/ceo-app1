// Real PostgreSQL adapter, locks and HTTP routes in a disposable test schema.
const {test}=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const pg=require('pg'),express=require('../monitorBP backend/node_modules/express');
const createWorkflow=require('../monitorBP backend/inspectionWorkflow');
const createRoutes=require('../monitorBP backend/inspectionRoutes');
const {createPermitSessions}=require('../monitorBP backend/permitSessions');
const valid={inspection_type:'Preliminary',inspection_date:'2026-10-12',inspector_name:'Inspector Cruz',result:'Scheduled',findings:'Site visit scheduled.',next_inspection_date:'2026-10-19'};

test('Building and Occupancy inspections preserve permissions, parent records and concurrent edits',async t=>{
    const config=JSON.parse(process.env.OFFICE_PG_CONNECTIONS||'[]').find(item=>item.source==='permit_system');
    assert.equal(config?.database,'permit_system_test','Must use the isolated local test database');
    const schema='inspection_verify_'+crypto.randomBytes(8).toString('hex');
    const owner=new pg.Client(config);await owner.connect();
    let pool,server;
    try {
        await owner.query('CREATE SCHEMA '+schema);await owner.query('SET search_path TO '+schema);
        await owner.query("CREATE TABLE users(id INT PRIMARY KEY,role VARCHAR(20),is_active INT,is_verified INT); INSERT INTO users VALUES (1,'operator',1,1),(2,'admin',1,1),(3,'superadmin',1,1),(4,'operator',0,1)");
        for(const table of ['permits','occupancy_permits'])await owner.query(`CREATE TABLE ${table}(id INT PRIMARY KEY,project_title TEXT); INSERT INTO ${table} VALUES (10,'Keep this permit'),(20,'Other permit')`);
        const migration=fs.readFileSync(path.join(__dirname,'../migration/permit-inspections.sql'),'utf8');
        // Idempotent migrations must preserve existing records.
        await owner.query(migration);await owner.query(migration);
        await owner.query(migration.replaceAll('permit_inspections','occupancy_inspections').replaceAll('permit_id','occupancy_id').replace('REFERENCES permits','REFERENCES occupancy_permits'));
        for(const [table,key,parent] of [['permit_change_requests','permit_id','permits'],['occupancy_change_requests','occupancy_id','occupancy_permits']])await owner.query(`CREATE TABLE ${table} (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,${key} INT REFERENCES ${parent}(id) ON DELETE CASCADE,requested_by INT,change_type VARCHAR(50),changes JSON,status VARCHAR(20),remarks TEXT,reviewed_by VARCHAR(50),reviewed_at TIMESTAMP)`);
        await owner.query('GRANT USAGE ON SCHEMA '+schema+' TO permit_app_migration');
        await owner.query('GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA '+schema+' TO permit_app_migration');
        await owner.query('GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA '+schema+' TO permit_app_migration');
        const RealPool=pg.Pool;
        pg.Pool=class extends RealPool {constructor(options){super({...options,options:options.options+' -c search_path='+schema+' -c role=permit_app_migration'});}};
        try {pool=require('./index').createPool({database:'permit_system'});}finally{pg.Pool=RealPool;}
        const adapter={promise:()=>pool,query(sql,args,callback){if(typeof args==='function'){callback=args;args=[];}pool.query(sql,args).then(([rows])=>callback(null,rows),callback);}};
        const sessions=createPermitSessions(adapter),workflows={};
        const app=express();app.use(express.json());
        // Fixture identity only; use the production authorization and DB actor checks.
        app.use((req,res,next)=>{const id=Number(req.get('x-fixture-user'));if(id)req.user={id,role:id===2?'admin':id===3?'superadmin':'operator'};next();});
        app.use(sessions.requireUser,sessions.protectWrites);
        for(const kind of ['permits','occupancy']) {
            const workflow=workflows[kind]=createWorkflow(()=>pool.getConnection(),kind);
            app.use('/api/'+kind+'/:id/inspections',createRoutes(workflow,sessions));
            for(const decision of ['approve','reject'])app.put('/api/'+kind+'/change-requests/:id/'+decision,sessions.requireRoles('admin'),workflow.review(decision),(req,res)=>res.status(404).json({success:false}));
        }
        app.use((error,req,res,next)=>res.status(error.status||500).json({success:false,message:'Invalid test request.'}));
        server=app.listen(0,'127.0.0.1');await new Promise(resolve=>server.once('listening',resolve));
        const origin='http://127.0.0.1:'+server.address().port;
        async function request(kind,suffix='',{method='GET',body,user=1,version='',parent=10,review}={}) {
            const url=origin+'/api/'+kind+(review?'/change-requests/'+review:'/'+parent+'/inspections'+suffix);
            const response=await fetch(url,{method,headers:{'x-fixture-user':String(user),'x-permit-request':'1','x-record-version':version,'Content-Type':'application/json',Origin:origin},...(body===undefined?{}:{body:JSON.stringify(body)})});
            return {code:response.status,body:await response.json()};
        }
        const list=async(kind,parent=10)=>(await request(kind,'',{parent})).body.inspections;
        const rows=async sql=>(await owner.query(sql)).rows;
        for(const kind of ['permits','occupancy']) {
            const table=kind==='permits'?'permit_inspections':'occupancy_inspections';
            const parentTable=kind==='permits'?'permits':'occupancy_permits';
            const requests=kind==='permits'?'permit_change_requests':'occupancy_change_requests';
            let id;
            await t.test(kind+': empty state, creation and office calendar dates',async()=>{
                assert.deepEqual(await list(kind),[]);
                const created=await request(kind,'',{method:'POST',body:valid});assert.equal(created.code,200);id=created.body.id;
                assert.ok(Number.isSafeInteger(id)&&id>0,'PostgreSQL insertId must be returned');
                const saved=(await list(kind))[0];assert.equal(saved.inspection_date,'2026-10-12');assert.equal(saved.next_inspection_date,'2026-10-19');assert.match(saved._version,/^[a-f0-9]{64}$/);
                assert.deepEqual(await list(kind,20),[]);
            });
            await t.test(kind+': validation and access failures save nothing',async()=>{
                for(const body of [null,{}, {...valid,inspector_name:' '},{...valid,findings:' '},{...valid,findings:'<br>'},{...valid,inspector_name:'A'.repeat(151)},{...valid,inspection_date:'2026-02-30'},{...valid,next_inspection_date:'2026-10-11'},{...valid,result:'Unknown'}])assert.equal((await request(kind,'',{method:'POST',body})).code,400);
                assert.equal((await request(kind,'',{method:'POST',body:valid,parent:999})).code,404);
                assert.equal((await request(kind,'',{parent:'invalid'})).code,400);
                assert.equal((await request(kind,'',{user:0})).code,401);
                for(const user of [2,3,4])assert.equal((await request(kind,'',{method:'POST',body:valid,user})).code,403);
                assert.equal((await list(kind)).length,1);
            });
            await t.test(kind+': updates require the loaded version and cannot cross parents',async()=>{
                const saved=(await list(kind))[0];
                assert.equal((await request(kind,'/'+id,{method:'PUT',body:{...valid,findings:'Changed'}})).code,409);
                assert.equal((await request(kind,'/'+id,{method:'PUT',parent:20,body:valid,version:saved._version})).code,404);
                assert.equal((await request(kind,'/'+id,{method:'DELETE',parent:20,version:saved._version})).code,404);
                const updated=await request(kind,'/'+id,{method:'PUT',body:{...valid,findings:'Changed'},version:saved._version});assert.equal(updated.code,200);
                assert.equal((await request(kind,'/'+id,{method:'PUT',body:valid,version:saved._version})).code,409);
                assert.equal((await list(kind))[0].findings,'Changed');
            });
            await t.test(kind+': simultaneous edits and deletion requests serialize safely',async()=>{
                const version=(await list(kind))[0]._version;
                const updates=await Promise.all(['First','Second'].map(findings=>request(kind,'/'+id,{method:'PUT',body:{...valid,findings},version})));
                assert.deepEqual(updates.map(result=>result.code).sort(),[200,409]);
                const current=(await list(kind))[0];
                const deletions=await Promise.all([1,2].map(()=>request(kind,'/'+id,{method:'DELETE',version:current._version})));
                assert.deepEqual(deletions.map(result=>result.code).sort(),[200,409]);
                assert.equal((await list(kind)).length,1);assert.equal((await rows('SELECT * FROM '+requests)).length,1);
                const requestId=(await rows('SELECT * FROM '+requests))[0].id;
                assert.equal((await request(kind,'',{method:'PUT',review:requestId+'/approve'})).code,403);
                assert.equal((await request(kind,'',{method:'PUT',user:2,review:requestId+'/reject'})).code,200);
                assert.equal((await list(kind)).length,1);
            });
            await t.test(kind+': changed inspections block approval; fresh approval removes only the child',async()=>{
                let current=(await list(kind))[0];
                await request(kind,'/'+id,{method:'DELETE',version:current._version});
                const outdated=(await rows("SELECT id FROM "+requests+" WHERE status='pending'"))[0].id;
                await request(kind,'/'+id,{method:'PUT',body:{...valid,findings:'Keep the newer inspection'},version:current._version});
                assert.equal((await request(kind,'',{method:'PUT',user:2,review:outdated+'/approve'})).code,409);
                current=(await list(kind))[0];assert.equal(current.findings,'Keep the newer inspection');
                await request(kind,'/'+id,{method:'DELETE',version:current._version});
                const fresh=(await rows("SELECT id FROM "+requests+" WHERE status='pending'"))[0].id;
                const reviews=await Promise.all(['approve','reject'].map(decision=>request(kind,'',{method:'PUT',user:2,review:fresh+'/'+decision})));
                assert.deepEqual(reviews.map(result=>result.code).sort(),[200,409]);
                const approved=(await rows('SELECT status FROM '+requests+' WHERE id='+fresh))[0].status==='approved';
                assert.equal((await list(kind)).length,approved?0:1);
                assert.equal((await rows('SELECT * FROM '+parentTable)).length,2);
            });
            await t.test(kind+': parent cascade retains the other permit type',async()=>{
                const created=await request(kind,'',{method:'POST',parent:20,body:valid});assert.equal(created.code,200);
                const other=kind==='permits'?'occupancy_permits':'permits';
                const count=(await rows('SELECT * FROM '+other)).length;
                await owner.query('DELETE FROM '+parentTable+' WHERE id=20');
                assert.equal((await rows('SELECT * FROM '+table+' WHERE '+(kind==='permits'?'permit_id':'occupancy_id')+'=20')).length,0);
                assert.equal((await rows('SELECT * FROM '+other)).length,count);
            });
        }
        await t.test('Building inspection audit captures the Building record rather than a matching Occupancy ID',async()=>{
            await owner.query("INSERT INTO permit_inspections(permit_id,inspection_type,inspection_date,inspector_name,result,findings) VALUES(10,'Special','2026-10-12','Building inspector','Passed','Building findings')");
            const saved=(await list('permits')).find(row=>row.inspector_name==='Building inspector');
            const changes=await require('../monitorBP backend/projectChanges').capture(async(sql,args)=>(await pool.query(sql,args))[0],'permits',10,'/inspections/'+saved.id,{findings:'New findings'});
            assert.deepEqual(changes,[{field:'Findings',before:'Building findings',after:'New findings'}]);
        });
        await t.test('failed insert rolls back and invalid workspace names cannot become SQL',async()=>{
            assert.throws(()=>createWorkflow(()=>pool.getConnection(),'untrusted_table'),/Unknown inspection/);
            const before=(await list('permits')).length;
            const workflow=createWorkflow(async()=>{const connection=await pool.getConnection();return {...connection,query(sql,args){if(sql.startsWith('INSERT INTO permit_inspections'))throw Error('Injected fixture failure');return connection.query(sql,args);}};},'permits');
            const res={code:200,status(code){this.code=code;return this;},json(body){this.body=body;}};
            await workflow.save()({user:{id:1,role:'operator'},params:{id:10},body:valid},res);
            assert.equal(res.code,500);assert.equal((await list('permits')).length,before);
        });
    } finally {
        if(server)await new Promise(resolve=>server.close(resolve));
        if(pool)await pool.end();
        await owner.query('SET search_path TO public');
        await owner.query('DROP SCHEMA IF EXISTS '+schema+' CASCADE');await owner.end();
    }
});
