const {test}=require('node:test'),assert=require('node:assert/strict');
const {createReader}=require('../monitorBP backend/permitAddedAt');
module.exports=(open,dialect)=>{
    test('system-added dates use stored creation events, imports and legacy history, never filing dates',async t=>{
        const db=await open();t.after(()=>db.end());
        const temp=dialect==='postgres'?'TEMP':'TEMPORARY',stamp=dialect==='postgres'?'TIMESTAMPTZ':'DATETIME';
        for(const [table,fields] of Object.entries({
            permits:`id INT PRIMARY KEY,created_at ${stamp},permit_date DATE`,occupancy_permits:'id INT PRIMARY KEY,date_applied DATE',
            permit_creation_requests:`kind VARCHAR(16),project_id INT,created_at ${stamp}`,
            project_records:`id INT ${dialect==='postgres'?'GENERATED BY DEFAULT AS IDENTITY':'AUTO_INCREMENT'} PRIMARY KEY,kind VARCHAR(16),project_id INT,category VARCHAR(16),outcome VARCHAR(20),message VARCHAR(100),created_at ${stamp}`,
            permit_import_batches:`kind VARCHAR(16),project_ids JSON,created_at ${stamp}`
        }))await db.query(`CREATE ${temp} TABLE ${table} (${fields})`);
        const added=new Date('2026-11-18T16:30:00Z'),later=new Date('2026-11-19T04:00:00Z'),old=new Date('2020-01-01T00:00:00Z');
        await db.query("INSERT INTO permits VALUES (1,?,'2020-01-01'),(2,NULL,'2020-01-01')",[added]);
        await db.query("INSERT INTO occupancy_permits VALUES(1,'2020-01-01'),(2,'2020-01-01'),(3,'2020-01-01'),(4,'2020-01-01'),(33,'2020-01-01')");
        await db.query("INSERT INTO permit_creation_requests VALUES('occupancy',1,?),('permits',2,?)",[added,added]);
        await db.query("INSERT INTO project_records (kind,project_id,category,outcome,message,created_at) VALUES('occupancy',1,'activity','saved','Created project',?),('occupancy',1,'activity','failed','Created project',?),('occupancy',1,'comment','saved','Created project',?),('occupancy',2,'activity','saved','Created project',?)",[later,old,old,added]);
        await db.query("INSERT INTO permit_import_batches VALUES('occupancy','[3,33]',?),('permits','[4]',?)",[added,old]);
        if(dialect==='postgres'){
            await db.query('GRANT SELECT ON pg_temp.permits,pg_temp.occupancy_permits,pg_temp.permit_creation_requests,pg_temp.project_records,pg_temp.permit_import_batches TO permit_app_migration');
            await db.query('SET ROLE permit_app_migration');
        }
        const reader=createReader({dialect,query:(...args)=>db.query(...args)});
        for(const [kind,id] of [['permits',1],['permits',2],['occupancy',1],['occupancy',2],['occupancy',3],['occupancy',33]])assert.equal(new Date(await reader(kind,id)).toISOString(),added.toISOString());
        assert.equal(await reader('occupancy',4),null);
        await assert.rejects(reader('occupancy',999),e=>e.status===404);
    });
};
