/** Step 2 only: generate empty, isolated PostgreSQL schemas from the reviewed inventory.
 * Unknown source types/defaults fail closed. Never executes SQL or copies records.
 */
const fs = require('node:fs');
const path = require('node:path');
const inventory = require('./mysql-schema-inventory.json');
const q = value => { if (!/^[a-zA-Z0-9_]+$/.test(value)) throw Error('Unsupported identifier'); return '"'+value+'"'; };
for (const source of ['permit_system', 'queue_system']) {
 const s = inventory.databases[source], target = source+'_migration';
 const role = source === 'permit_system' ? 'permit_app_migration' : 'queue_app_migration';
 const sql = [`-- Generated by generate-postgres-schema.cjs. Empty migration database only.`, 'BEGIN;',
 `DO $$ BEGIN IF current_database() <> '${target}' OR EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema='public') THEN RAISE EXCEPTION 'Expected empty ${target}'; END IF; END $$;`,
 `CREATE COLLATION public.app_ci (provider=icu, locale='und-u-ks-level1', deterministic=false);`];
 for (const t of s.tables) {
  const fields = s.columns.filter(c=>c.TABLE_NAME===t.TABLE_NAME).map(c=>{
   let type = c.COLUMN_TYPE, extra = '';
   if (/^int\(/.test(type)) type='integer';
   else if (/^bigint\(/.test(type)) { if(type.includes('unsigned')) extra=` CHECK (${q(c.COLUMN_NAME)} >= 0)`; type='bigint'; }
   else if(type==='tinyint(1)') { type='smallint'; extra=` CHECK (${q(c.COLUMN_NAME)} BETWEEN -128 AND 127)`; }
   else if(['text','mediumtext','longtext'].includes(type)) type='text';
   else if(type==='timestamp') type='timestamp(0) with time zone';
   else if(/^datetime(?:\(\d\))?$/.test(type)) type=`timestamp(${type.match(/\((\d)\)/)?.[1]||0}) without time zone`;
   else if(type.startsWith('enum(')) { extra=` CHECK (${q(c.COLUMN_NAME)} IN (${type.slice(5,-1)}))`; type='text'; }
   else if(!/^(?:var)?char\(\d+\)$/.test(type) && type!=='date') throw Error('Unsupported type '+type);
   let line=q(c.COLUMN_NAME)+' '+type;
   if(c.COLLATION_NAME) line+=' COLLATE '+(c.COLLATION_NAME.endsWith('_ci')?'public.app_ci':'"C"');
   if(c.EXTRA==='auto_increment') {
    if(!Number.isSafeInteger(Number(t.AUTO_INCREMENT)) || Number(t.AUTO_INCREMENT)<1) throw Error('Invalid identity watermark');
    line+=` GENERATED BY DEFAULT AS IDENTITY (START WITH ${t.AUTO_INCREMENT})`;
   } else if(c.COLUMN_DEFAULT!==null) {
    const d=c.COLUMN_DEFAULT;
    if(d==='current_timestamp()') line+=' DEFAULT CURRENT_TIMESTAMP';
    else if(d==='NULL'||/^-?\d+$/.test(d)||/^'(?:[^'\\]|'')*'$/.test(d)) line+=' DEFAULT '+d;
    else throw Error('Unsupported default '+d);
   }
   if(c.IS_NULLABLE==='NO') line+=' NOT NULL';
   return line+extra;
  });
  const groups=Object.groupBy(s.indexes.filter(i=>i.TABLE_NAME===t.TABLE_NAME),i=>i.INDEX_NAME);
  for(const [name,cols] of Object.entries(groups)) {
   if(cols.some(c=>c.SUB_PART)) throw Error('Prefix index requires review');
   if(name==='PRIMARY'||!cols[0].NON_UNIQUE) fields.push((name==='PRIMARY'?'PRIMARY KEY':'UNIQUE')+' ('+cols.map(c=>q(c.COLUMN_NAME)).join(', ')+')');
  }
  for(const c of s.checks.filter(c=>c.TABLE_NAME===t.TABLE_NAME)) {
   const match=/^json_valid\(`([a-z_]+)`\)$/i.exec(c.CHECK_CLAUSE);
   if(!match) throw Error('Unsupported check '+c.CHECK_CLAUSE);
   fields.push(`CHECK (${q(match[1])} IS NULL OR ${q(match[1])} IS JSON)`);
  }
  sql.push(`CREATE TABLE public.${q(t.TABLE_NAME)} (\n  ${fields.join(',\n  ')}\n);`);
  for(const [name,cols] of Object.entries(groups)) if(name!=='PRIMARY'&&cols[0].NON_UNIQUE) sql.push(`CREATE INDEX ${q(t.TABLE_NAME+'_'+name)} ON public.${q(t.TABLE_NAME)} (${cols.map(c=>q(c.COLUMN_NAME)).join(', ')});`);
 }
 for(const fk of s.foreignKeys) sql.push(`ALTER TABLE public.${q(fk.TABLE_NAME)} ADD CONSTRAINT ${q(fk.CONSTRAINT_NAME)} FOREIGN KEY (${q(fk.COLUMN_NAME)}) REFERENCES public.${q(fk.REFERENCED_TABLE_NAME)} (${q(fk.REFERENCED_COLUMN_NAME)}) ON UPDATE ${fk.UPDATE_RULE} ON DELETE ${fk.DELETE_RULE};`);
 if(source==='permit_system') sql.push(`CREATE FUNCTION public.touch_checklist_updated_at() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog AS $$ BEGIN IF NEW IS DISTINCT FROM OLD AND NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN NEW.updated_at=statement_timestamp(); END IF; RETURN NEW; END $$;`,
 `REVOKE ALL ON FUNCTION public.touch_checklist_updated_at() FROM PUBLIC;`,
 `CREATE TRIGGER checklist_updated_at BEFORE UPDATE ON public.occupancy_checklists FOR EACH ROW EXECUTE FUNCTION public.touch_checklist_updated_at();`);
 if(source==='permit_system')sql.push(fs.readFileSync(path.join(__dirname,'permit-session-notices.sql'),'utf8'));
 sql.push(`GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO ${q(role)};`, `GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO ${q(role)};`, 'COMMIT;');
 fs.writeFileSync(path.join(__dirname,target+'.sql'),sql.join('\n\n')+'\n');
 console.log(`${target}: ${s.tables.length} tables, ${s.columns.length} columns, ${s.foreignKeys.length} foreign keys`);
}
