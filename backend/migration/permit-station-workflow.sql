BEGIN;
CREATE TABLE IF NOT EXISTS permit_station_assignments (
 user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 station_key varchar(120) NOT NULL,
 station_name varchar(100) NOT NULL,
 updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (user_id,station_key)
);
CREATE TABLE IF NOT EXISTS permit_final_reviews (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kind varchar(16) NOT NULL CHECK (kind IN ('permits','occupancy')),
 project_id integer NOT NULL,
 decision varchar(16) NOT NULL CHECK (decision IN ('approved','returned','invalidated')),
 reviewer_id integer,
 reviewer_name varchar(100) NOT NULL,
 remarks text NOT NULL DEFAULT '',
 snapshot_hash char(64) NOT NULL,
 snapshot jsonb NOT NULL,
 created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS permit_final_reviews_project ON permit_final_reviews(kind,project_id,id DESC);
GRANT SELECT,INSERT,UPDATE,DELETE ON permit_station_assignments TO permit_app_migration;
GRANT SELECT,INSERT ON permit_final_reviews TO permit_app_migration;
GRANT USAGE,SELECT ON SEQUENCE permit_final_reviews_id_seq TO permit_app_migration;
COMMIT;
