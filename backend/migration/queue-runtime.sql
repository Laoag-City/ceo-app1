DO $$ BEGIN
 IF current_database() NOT IN ('queue_system_migration','queue_system_test') THEN
  RAISE EXCEPTION 'Expected the configured queue database';
 END IF;
END $$;
CREATE TABLE IF NOT EXISTS public.queue_client_history_archive (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id bigint NOT NULL,
 name varchar(255) COLLATE public.app_ci NOT NULL,
 phone varchar(50) COLLATE public.app_ci,
 barangay varchar(255) COLLATE public.app_ci NOT NULL,
 reason text COLLATE public.app_ci NOT NULL,
 status text COLLATE public.app_ci CHECK (status IN ('waiting','holding','serving','dropped','completed')),
 created_at timestamp(0) with time zone NOT NULL,
 called_by varchar(50) COLLATE public.app_ci,
 archived_at timestamp(0) with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS queue_client_history_created
 ON public.queue_client_history_archive (created_at DESC,ticket_id DESC,id DESC);
REVOKE ALL ON public.queue_client_history_archive FROM PUBLIC,queue_app_migration;
GRANT SELECT ON public.queue_client_history_archive TO queue_app_migration;
REVOKE ALL ON SEQUENCE public.queue_client_history_archive_id_seq FROM PUBLIC,queue_app_migration;
-- Stable visit identity survives reset and reused ticket numbering. Tracking is
