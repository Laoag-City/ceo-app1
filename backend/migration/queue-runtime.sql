CREATE OR REPLACE FUNCTION public.reset_office_queue() RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(hashtextextended('queue_system:service-transitions',0));
 LOCK TABLE public.tickets,public.ticket_submission_keys,public.active_workstations,public.queue_client_history_archive IN ACCESS EXCLUSIVE MODE;
 UPDATE public.tickets SET report_visit_id=gen_random_uuid()::text WHERE report_visit_id IS NULL;
 INSERT INTO public.queue_client_history_archive (ticket_id,name,phone,barangay,reason,status,created_at,called_by,report_visit_id,report_tracking_started,first_called_at,completed_at,dropped_at,service_started_at,service_ms)
 SELECT id,name,phone,barangay,reason,status,created_at,called_by,report_visit_id,report_tracking_started,first_called_at,completed_at,dropped_at,service_started_at,service_ms FROM public.tickets;
 UPDATE public.ticket_submission_keys SET ticket_id=NULL;
 DELETE FROM public.tickets;
 DELETE FROM public.active_workstations;
 ALTER SEQUENCE public.tickets_id_seq RESTART WITH 1001;
END $$;
REVOKE ALL ON FUNCTION public.reset_office_queue() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.reset_office_queue() TO queue_app_migration;
COMMIT;
