-- Additive migration; never copies or changes existing permit/occupancy records.
CREATE TABLE IF NOT EXISTS permit_inspections (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permit_id INTEGER NOT NULL REFERENCES permits(id) ON DELETE CASCADE,
    inspection_type VARCHAR(50) NOT NULL DEFAULT 'Preliminary'
        CHECK (inspection_type IN ('Preliminary','Final','Follow-up','Special')),
    inspection_date DATE NOT NULL,
    inspector_name VARCHAR(150) NOT NULL CHECK (length(trim(inspector_name)) > 0),
    result VARCHAR(50) NOT NULL DEFAULT 'Scheduled'
        CHECK (result IN ('Scheduled','Passed','Failed','Conditional')),
    findings TEXT NOT NULL CHECK (length(trim(findings)) > 0),
    next_inspection_date DATE CHECK (next_inspection_date >= inspection_date),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS permit_inspections_parent_date
    ON permit_inspections (permit_id, inspection_date DESC, id DESC);
