-- Additive Building document checklist; one row per parent permit.
CREATE TABLE IF NOT EXISTS permit_checklists (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permit_id INTEGER NOT NULL UNIQUE REFERENCES permits(id) ON DELETE CASCADE,
    checklist_state JSONB NOT NULL DEFAULT '{}'::jsonb
        CHECK (jsonb_typeof(checklist_state) = 'object'),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
