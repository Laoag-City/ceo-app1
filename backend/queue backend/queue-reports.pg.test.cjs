const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {createQueueService} = require('./queue-service');
const {createQueueReports} = require('./queue-reports');
const {createTicketSubmission} = require('./ticket-submission');

test('PostgreSQL report timing, Manila midnight, and reset preservation use isolated temporary fixtures', {skip:process.env.DB_ENGINE !== 'postgres'}, async () => {
    const settings=JSON.parse(process.env.OFFICE_PG_CONNECTIONS || '[]');
    assert.equal(settings[0]?.database,'queue_system_test','Run with the isolated Verify-QueueWindows.ps1 test connection.');
    const pool=require('../database').createPool({database:'queue_system'});
    const conn=await pool.getConnection();
    try {
        await conn.query(`CREATE TEMP TABLE tickets (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name TEXT,phone TEXT,email TEXT,barangay TEXT,reason TEXT,
            status TEXT DEFAULT 'waiting',called_by TEXT,recall_stamp BIGINT,created_at TIMESTAMPTZ(3) DEFAULT CURRENT_TIMESTAMP,
            report_visit_id CHAR(36),report_tracking_started SMALLINT DEFAULT 0,first_called_at TIMESTAMPTZ(3),
            completed_at TIMESTAMPTZ(3),dropped_at TIMESTAMPTZ(3),service_started_at TIMESTAMPTZ(3),service_ms BIGINT DEFAULT 0)`);
        await conn.query(`CREATE TEMP TABLE queue_client_history_archive (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,ticket_id BIGINT,name TEXT,phone TEXT,barangay TEXT,reason TEXT,
            status TEXT,created_at TIMESTAMPTZ(3),called_by TEXT,report_visit_id CHAR(36),report_tracking_started SMALLINT DEFAULT 0,
            first_called_at TIMESTAMPTZ(3),completed_at TIMESTAMPTZ(3),dropped_at TIMESTAMPTZ(3),service_started_at TIMESTAMPTZ(3),service_ms BIGINT DEFAULT 0)`);
        await conn.query('CREATE TEMP TABLE ticket_submission_keys (request_id CHAR(36) PRIMARY KEY,fingerprint CHAR(64),ticket_id BIGINT,created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP)');
        await conn.query('CREATE TEMP TABLE active_workstations (workspace TEXT PRIMARY KEY)');
        for (const table of ['tickets','queue_client_history_archive','ticket_submission_keys','active_workstations']) {
            await conn.query(`GRANT SELECT,INSERT,UPDATE,DELETE ON ${table} TO queue_app_migration`);
        }
        await conn.query('GRANT USAGE,SELECT ON SEQUENCE pg_temp.tickets_id_seq,pg_temp.queue_client_history_archive_id_seq TO queue_app_migration');
        // Execute the actual owner-reset definition against TEMP tables only. No
        // public function, live queue, or persistent sequence is ever invoked.
        const migration=fs.readFileSync(path.join(__dirname,'../migration/queue-runtime.sql'),'utf8');
        const resetDefinition=migration.match(/CREATE OR REPLACE FUNCTION public\.reset_office_queue\(\)[\s\S]*?END \$\$;/)[0];
        await conn.query(resetDefinition.replace(/public\./g,'pg_temp.').replace('pg_temp.reset_office_queue()','pg_temp.report_fixture_reset()'));
        await conn.query('GRANT EXECUTE ON FUNCTION pg_temp.report_fixture_reset() TO queue_app_migration');
        await conn.query('SET ROLE queue_app_migration');
        const adapter={dialect:'postgres',query:conn.query.bind(conn),getConnection:async()=>({...conn,release(){}})};
        let at='2026-10-07T16:01:00Z';
        const action=createQueueService(adapter,'queue-report-fixture:'+process.pid,{now:()=>at});
        const report=createQueueReports(adapter);
        for (const [id,reason,status,created,tracked] of [
            [1001,'Releasing Bldg. Permit','completed','2026-10-07T15:59:00Z',0],
            [1002,'Releasing Bldg. Permit','waiting','2026-10-07T16:00:00Z',1],
            [1003,'Releasing Bldg. Occupancy','waiting','2026-10-07T16:00:00Z',1],
            [1004,'Inquire','waiting','2026-10-07T16:00:00Z',1]
        ]) await conn.query('INSERT INTO tickets (id,name,reason,status,created_at,report_visit_id,report_tracking_started) VALUES (?,?,?,?,?,?,?)',[id,'Fixture visitor',reason,status,new Date(created),'00000000-0000-4000-8000-'+String(id).padStart(12,'0'),tracked]);
        await conn.query("UPDATE tickets SET called_by='PC1' WHERE id=1001");
        await action('call-next',{workspace:'PC3',source:'queue'});
        const [[firstCall]]=await conn.query('SELECT first_called_at,service_started_at FROM tickets WHERE id=1002');
        at='2026-10-07T16:01:30Z';
        await action('recall',{workspace:'PC3',ticketId:'TKT-1002'});
        const [[afterRecall]]=await conn.query('SELECT first_called_at,service_started_at FROM tickets WHERE id=1002');
        assert.deepEqual(afterRecall,firstCall,'Recalling must not restart first wait or active service');
        at='2026-10-07T16:02:00Z';
        await action('hold',{workspace:'PC3',ticketId:'TKT-1002'});
        at='2026-10-07T16:12:00Z';
        await action('resume',{workspace:'PC3',ticketId:'TKT-1002',currentTicketId:null});
        at='2026-10-07T16:15:00Z';
        await action('next',{workspace:'PC3',ticketId:'TKT-1002'});
        at='2026-10-07T16:18:00Z';
        await action('drop',{workspace:'PC1',ticketId:'TKT-1004',expectedStatus:'waiting'});
        const before=await report({from:'2026-10-07',to:'2026-10-08'});
        assert.equal(before.summary.registered,4);
        assert.equal(before.summary.completed,2);
        assert.equal(before.summary.dropped,1);
        assert.equal(before.summary.averageWaitSeconds,60);
        assert.equal(before.summary.averageServiceSeconds,240,'Ten minutes held are excluded');
        assert.deepEqual(before.daily.map(day=>day.registered),[1,3]);
        assert.deepEqual(before.timingCoverage,{measured:1,total:4,waitMeasured:1,serviceMeasured:1});
        assert.equal(before.daily[0].averageServiceSeconds,null,'Legacy completion is unavailable, not zero');
        assert.deepEqual(before.windows.map(window=>window.registered),[2,1,1]);
        const legacyFilters={from:'2026-10-07',to:'2026-10-08',window:'PC1',service:'Releasing Bldg. Permit'};
        const historical=await report(legacyFilters);
        assert.equal(historical.summary.registered,1,'The old building release remains at its recorded Window 1');
        assert.equal(historical.summary.completed,1);
        await conn.query('SELECT pg_temp.report_fixture_reset()');
        const [[archived]]=await conn.query('SELECT report_visit_id,service_ms,first_called_at FROM queue_client_history_archive WHERE ticket_id=1002');
        assert.equal(archived.report_visit_id,'00000000-0000-4000-8000-000000001002');
        assert.equal(archived.service_ms,240000);
        assert.deepEqual(await report({from:'2026-10-07',to:'2026-10-08'}),before,'Reset keeps the whole report cohort unchanged');
        assert.deepEqual(await report(legacyFilters),historical,'Archiving preserves old service/window pairs too');

        const submission=createTicketSubmission(adapter);
        const payload={requestId:'11111111-1111-4111-8111-111111111111',name:'New fixture',phone:'09123456789',email:'',barangay:'Test',reason:'Releasing Bldg. Occupancy'};
        const registered=await submission.submit(payload);
        const repeated=await submission.submit(payload);
        assert.equal(registered.ticketId,'TKT-1001','Reset restarts the public ticket number');
        assert.equal(repeated.ticketId,registered.ticketId);
        assert.equal(repeated.duplicate,true);
        const [[fresh]]=await conn.query('SELECT report_visit_id,report_tracking_started FROM tickets WHERE id=1001');
        assert.equal(fresh.report_tracking_started,1);
        assert.match(fresh.report_visit_id,/^[a-f0-9-]{36}$/);
        assert.notEqual(fresh.report_visit_id,'00000000-0000-4000-8000-000000001001','Reused number receives an independent visit identity');
        const [[counts]]=await conn.query('SELECT COUNT(*) AS count FROM tickets');
        assert.equal(counts.count,1,'Registration retry does not inflate counts');
    } finally {conn.release();await pool.end();}
});
